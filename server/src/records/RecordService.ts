/**
 * F3.4 dated records for the firm's eQMS (UI 2.0 §5.4, FR-14.15/14.18): the project record,
 * the problem log and the client request log, as PDF or DOCX, generated from the project data
 * at that moment. Every generation is logged with the SHA-256 of the bytes handed out, so a
 * record filed in the eQMS can be matched to what the tool produced and when.
 */

export type RecordKind = 'project_record' | 'problem_log' | 'request_log';
export type RecordFormat = 'pdf' | 'docx';
export const RECORD_KINDS: readonly RecordKind[] = ['project_record', 'problem_log', 'request_log'];

const KIND_TITLE: Record<RecordKind, string> = { project_record: 'Project record', problem_log: 'Problem log', request_log: 'Client request log' };

export interface ProjectHeader {
  projectId: string;
  projectName: string;
  submissionType: string;
  estarTemplate: string;
  clientName: string;
  deviceName: string;
  productCode: string | null;
  deviceClass: string | null;
}

export interface RecordExport {
  id: string;
  kind: RecordKind;
  format: RecordFormat;
  sha256: string;
  sizeBytes: number;
  estarTemplate: string;
  createdBy: string | null;
  createdAt: string;
}

const fmtDate = (d: Date | string | null): string => (d ? new Date(d).toISOString().slice(0, 10) : '');
const size = (b: number | null): string => (b === null ? 'unknown' : b >= 1e9 ? `${(b / 1e9).toFixed(2)} GB` : b >= 1e6 ? `${(b / 1e6).toFixed(1)} MB` : `${Math.max(1, Math.round(b / 1e3))} KB`);
const STATUS: Record<string, string> = { not_started: 'Not started', drafting: 'Drafting', in_review: 'In review', approved: 'Approved' };

export async function projectHeader(orgId: string, projectId: string): Promise<ProjectHeader> {
  const [p] = await dataService.query<{
    name: string;
    submission_type: string;
    estar_template: string;
    client_name: string;
    device_name: string;
    product_code: string | null;
    device_class: string | null;
  }>(
    { orgId },
    'projects',
    `SELECT p.name, p.submission_type, p.estar_template, w.name AS client_name, d.name AS device_name, d.product_code, d.device_class
       FROM projects p JOIN devices d ON d.id = p.device_id AND d.org_id = p.org_id
       JOIN client_workspaces w ON w.id = p.workspace_id AND w.org_id = p.org_id
      WHERE p.id = $1 AND p.org_id = $2`,
    [projectId, orgId],
  );
  if (!p) throw new AppError(404, ErrorCodes.NOT_FOUND, 'Project not found');
  return {
    projectId,
    projectName: p.name,
    submissionType: p.submission_type,
    estarTemplate: p.estar_template,
    clientName: p.client_name,
    deviceName: p.device_name,
    productCode: p.product_code,
    deviceClass: p.device_class,
  };
}

export function headerBlocks(kind: RecordKind, h: ProjectHeader, at: Date, by: string): Block[] {
  return [
    { kind: 'title', text: `${KIND_TITLE[kind]}: ${h.projectName}` },
    { kind: 'subtitle', text: `Dated ${at.toISOString().replace('T', ' ').slice(0, 16)} UTC` },
    {
      kind: 'fields',
      rows: [
        ['Client', h.clientName],
        ['Device', `${h.deviceName}${h.productCode ? `, product code ${h.productCode}` : ''}${h.deviceClass ? `, class ${h.deviceClass}` : ''}`],
        ['Submission', `${h.submissionType} 510(k)`],
        ['eSTAR template', h.estarTemplate],
        ['Generated by', `${by}, with MedexRegAI`],
      ],
    },
  ];
}

const CLOSING: Block = {
  kind: 'note',
  text: 'Generated by MedexRegAI from the project data at the date above, for the firm’s quality records. It is not a submission: the consultant reviews, files and signs.',
};

async function projectRecordBlocks(orgId: string, h: ProjectHeader): Promise<Block[]> {
  const board = await sectionService.board(orgId, h.projectId);
  const readiness = await readinessService.check(orgId, h.projectId);
  const files = await dataService.query<{ name: string; version_no: number | null; created_at: Date | null; sha256: string | null; size_bytes: string | null; section: string | null }>(
    { orgId },
    'files',
    `SELECT f.name, v.version_no, v.created_at, v.sha256, v.size_bytes, s.title AS section
       FROM files f
       LEFT JOIN file_versions v ON v.id = f.current_version_id AND v.org_id = f.org_id
       LEFT JOIN file_assignments a ON a.file_id = f.id AND a.org_id = f.org_id AND a.is_current
       LEFT JOIN estar_sections s ON s.id = a.section_id
      WHERE f.org_id = $1 AND f.project_id = $2 AND f.status = 'active'
      ORDER BY s.ordinal NULLS LAST, f.name`,
    [orgId, h.projectId],
  );
  const issues = readiness.attachments.flatMap((a) => a.issues.map((i) => ({ a, i })));
  return [
    { kind: 'h2', text: 'Sections' },
    {
      kind: 'table',
      columns: [
        { label: 'eSTAR section', width: 3 },
        { label: 'Status', width: 1.2 },
        { label: 'Reviewer', width: 1.5 },
        { label: 'Approved', width: 1.8 },
        { label: 'Files', width: 0.7 },
        { label: 'Open problems', width: 1 },
      ],
      rows: board.sections.map((s) => [
        s.title,
        STATUS[s.status] ?? s.status,
        s.reviewer?.name ?? '',
        s.approvedBy ? `${s.approvedBy}, ${fmtDate(s.approvedAt)}` : '',
        String(s.fileCount),
        String(s.openProblems),
      ]),
    },
    { kind: 'h2', text: 'eSTAR attachment checks' },
    {
      kind: 'p',
      text: `${readiness.counts.attachments} attachments, ${size(readiness.totalBytes)} of the ${size(readiness.totalLimitBytes)} eSTAR limit (${readiness.totalPercent}%). ${readiness.counts.errors} error(s), ${readiness.counts.warnings} warning(s). Rules: ${readiness.template.label}, from FDA's eSTAR page (content current as of ${readiness.rules.source.contentAsOf}).`,
    },
    ...(issues.length
      ? [
          {
            kind: 'table' as const,
            columns: [
              { label: 'Attachment', width: 3 },
              { label: 'Severity', width: 1 },
              { label: 'Finding', width: 4 },
            ],
            rows: issues.map(({ a, i }) => [a.name, i.severity, i.message]),
          },
        ]
      : [{ kind: 'p' as const, text: 'No attachment issues.' }]),
    { kind: 'h2', text: 'Client files' },
    {
      kind: 'table',
      columns: [
        { label: 'File', width: 3 },
        { label: 'Section', width: 2 },
        { label: 'Version', width: 0.8 },
        { label: 'Received', width: 1.1 },
        { label: 'Size', width: 0.9 },
        { label: 'SHA-256 (first 16)', width: 1.7 },
      ],
      rows: files.map((f) => [
        f.name,
        f.section ?? 'Not filed',
        f.version_no ? `v${f.version_no}` : '',
        fmtDate(f.created_at),
        size(f.size_bytes === null ? null : Number(f.size_bytes)),
        f.sha256 ? f.sha256.slice(0, 16) : '',
      ]),
    },
  ];
}

export const recordService = {
  async generate(
    orgId: string,
    userId: string,
    projectId: string,
    kind: RecordKind,
    format: RecordFormat,
  ): Promise<{ fileName: string; contentType: string; bytes: Buffer; record: RecordExport }> {
    const h = await projectHeader(orgId, projectId);
    const [me] = await dataService.query<{ full_name: string }>({ orgId }, 'user_profiles', 'SELECT full_name FROM user_profiles WHERE user_id = $1', [userId]);
    const at = new Date();
    const body =
      kind === 'project_record' ? await projectRecordBlocks(orgId, h) : kind === 'problem_log' ? await problemLogBlocks(orgId, projectId) : await requestLogBlocks(orgId, projectId);
    const blocks = [...headerBlocks(kind, h, at, me?.full_name ?? 'A consultant'), ...body, CLOSING];
    const doc = { title: `${KIND_TITLE[kind]}: ${h.projectName}`, footer: `${h.projectName} · ${KIND_TITLE[kind]} · ${at.toISOString().slice(0, 10)}`, createdAt: at, blocks };
    const bytes = format === 'pdf' ? renderPdf(doc) : await renderDocx(doc);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const [row] = await dataService.query<{ id: string }>(
      { orgId, userId },
      'record_exports',
      `INSERT INTO record_exports (org_id, project_id, kind, format, sha256, size_bytes, estar_template, created_by, created_at)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9) RETURNING id`,
      [orgId, projectId, kind, format, sha256, bytes.length, h.estarTemplate, userId, at],
    );
    const safe = h.projectName.replace(/[^A-Za-z0-9 ()&,.-]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60) || 'Project';
    return {
      fileName: `${safe} - ${KIND_TITLE[kind]} ${at.toISOString().slice(0, 10)}.${format}`,
      contentType: format === 'pdf' ? 'application/pdf' : 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      bytes,
      record: { id: row.id, kind, format, sha256, sizeBytes: bytes.length, estarTemplate: h.estarTemplate, createdBy: me?.full_name ?? null, createdAt: at.toISOString() },
    };
  },

  /** Records generated for the project, newest first. */
  async history(orgId: string, projectId: string): Promise<RecordExport[]> {
    await projectHeader(orgId, projectId);
    const rows = await dataService.query<{
      id: string;
      kind: RecordKind;
      format: RecordFormat;
      sha256: string;
      size_bytes: number;
      estar_template: string;
      created_by: string | null;
      created_at: Date;
    }>(
      { orgId },
      'record_exports',
      `SELECT r.id, r.kind, r.format, r.sha256, r.size_bytes, r.estar_template, u.full_name AS created_by, r.created_at
         FROM record_exports r LEFT JOIN user_profiles u ON u.user_id = r.created_by
        WHERE r.org_id = $1 AND r.project_id = $2 ORDER BY r.created_at DESC LIMIT 100`,
      [orgId, projectId],
    );
    return rows.map((r) => ({
      id: r.id,
      kind: r.kind,
      format: r.format,
      sha256: r.sha256,
      sizeBytes: r.size_bytes,
      estarTemplate: r.estar_template,
      createdBy: r.created_by,
      createdAt: r.created_at.toISOString(),
    }));
  },
};
